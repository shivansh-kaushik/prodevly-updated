/**
 * `npm run posters` - renders the posters the page shows before the canvas has drawn,
 * on tier 0 (no WebGL, Save-Data, a weak GPU) and after a context loss: one transparent
 * AVIF per station and aspect bucket, cropped to the station's safe rect, drawn by the
 * real stage in Chrome against a running `npm run dev` (`/dev/home`, sample records).
 *
 * Posters show the REFERENCE composition: the counts of the sample records, not of the
 * page's real records. They are decoration (aria-hidden), shown only while the canvas
 * is not. Re-run after any change to the totem or its poses, and commit the result.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { chromium, type Page } from '@playwright/test';
import sharp from 'sharp';

const BASE = process.env.STAGE_URL ?? 'http://localhost:3050';
const DESIGN = process.argv[2] ?? 'keycap';
const OUT = `public/posters/${DESIGN}`;
const BUCKETS = [
  { name: 'tall', viewport: { width: 390, height: 844 }, scale: 2 },
  { name: 'wide', viewport: { width: 1440, height: 900 }, scale: 1.5 },
] as const;

interface Hook {
  stage: { status: string; stats: { target: number; subject: number; camera: number; opacity: number; safe: { x: number; y: number; w: number; h: number } } };
  scroll: { keys: string[] };
}

async function toStation(page: Page, key: string) {
  await page.evaluate((k) => {
    const el = document.querySelector(`[data-chapter="${k}"]`);
    if (!el) return;
    const r = el.getBoundingClientRect();
    window.scrollTo(0, r.top + window.scrollY + r.height / 2 - window.innerHeight / 2);
  }, key);
  await page.waitForFunction(
    (k) => {
      const h = (window as unknown as { __stage: Hook }).__stage;
      const at = h.scroll.keys.indexOf(k);
      const s = h.stage.stats;
      return at >= 0 && Math.abs(s.target - at) < 0.001 && Math.abs(s.subject - at) < 0.002 && Math.abs(s.camera - at) < 0.002 && s.opacity > 0.99;
    },
    key,
    { timeout: 15_000 },
  );
}

async function main() {
  mkdirSync(OUT, { recursive: true });
  const browser = await chromium.launch({ channel: 'chrome', args: ['--use-angle=metal', '--enable-webgl', '--ignore-gpu-blocklist', '--enable-gpu'] });
  const manifest: Record<string, Record<string, { w: number; h: number }>> = {};
  for (const bucket of BUCKETS) {
    const context = await browser.newContext({
      viewport: bucket.viewport,
      deviceScaleFactor: bucket.scale,
      hasTouch: bucket.name === 'tall',
      isMobile: bucket.name === 'tall',
    });
    const page = await context.newPage();
    await page.goto(`${BASE}/dev/home?tier=3`, { waitUntil: 'networkidle' });
    await page.waitForFunction(() => (window as unknown as { __stage?: Hook }).__stage?.stage.status === 'ready', undefined, { timeout: 30_000 });
    const keys = await page.evaluate(() => (window as unknown as { __stage: Hook }).__stage.scroll.keys);
    // Only the canvas: hide the page and the dev overlay, let the page background go transparent.
    await page.addStyleTag({ content: 'html,body,.pd-site{background:transparent!important}main,header,footer,dialog,nextjs-portal,.pd-stage-debug{visibility:hidden!important}' });
    for (const key of keys) {
      await toStation(page, key);
      await page.waitForTimeout(500);
      const safe = await page.evaluate(() => (window as unknown as { __stage: Hook }).__stage.stage.stats.safe);
      const { width, height } = bucket.viewport;
      const clip = {
        x: Math.max(0, Math.floor(safe.x * width)),
        y: Math.max(0, Math.floor(safe.y * height)),
        width: Math.min(width, Math.ceil(safe.w * width)),
        height: Math.min(height, Math.ceil(safe.h * height)),
      };
      clip.width = Math.min(clip.width, width - clip.x);
      clip.height = Math.min(clip.height, height - clip.y);
      const png = await page.screenshot({ omitBackground: true, clip });
      const file = `${OUT}/${key}-${bucket.name}.avif`;
      const info = await sharp(png).avif({ quality: 52, effort: 6 }).toFile(file);
      (manifest[key] ??= {})[bucket.name] = { w: info.width, h: info.height };
      console.log(`${file}  ${info.width}x${info.height}  ${(info.size / 1024).toFixed(1)} KB`);
    }
    await context.close();
  }
  await browser.close();
  const body = Object.entries(manifest)
    .map(([k, v]) => `  ${k}: { tall: { w: ${v.tall?.w}, h: ${v.tall?.h} }, wide: { w: ${v.wide?.w}, h: ${v.wide?.h} } },`)
    .join('\n');
  writeFileSync(
    'src/components/home/posters.generated.ts',
    `// Generated by \`npm run posters\`. Do not edit.\nexport const POSTERS: Record<string, { tall: { w: number; h: number }; wide: { w: number; h: number } }> = {\n${body}\n};\n`,
  );
  console.log('wrote src/components/home/posters.generated.ts');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
